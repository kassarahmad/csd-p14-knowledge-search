"""Contract conformance: the running code must match the frozen contract in contracts/.

1. The OpenAPI document generated by the app equals contracts/openapi/p14-search.yaml.
2. Each frozen JSON Schema has the same properties/required fields as the OpenAPI component of that name.
3. Real API outputs (produced here) and every example in contracts/examples validate against the frozen schemas.
"""

import json
from pathlib import Path

import pytest
import yaml
from jsonschema import Draft202012Validator

from p14_search.api.app import create_app
from p14_search.config import Settings
from p14_search.contracts import CONTRACT_MODELS

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = ROOT / "contracts" / "schemas"
OPENAPI = ROOT / "contracts" / "openapi" / "p14-search.yaml"


def frozen(name: str) -> dict:
    return json.loads((SCHEMAS / f"{name}.json").read_text(encoding="utf-8"))


def validate(name: str, instance) -> None:
    errors = sorted(Draft202012Validator(frozen(name)).iter_errors(instance), key=str)
    assert not errors, f"{name}: " + "; ".join(e.message for e in errors[:5])


def test_openapi_matches_frozen_spec():
    spec = create_app(Settings(_env_file=None), init_services=False).openapi()
    # Round-trip through YAML so both sides have the same types.
    assert yaml.safe_load(yaml.safe_dump(spec, sort_keys=False)) == yaml.safe_load(OPENAPI.read_text(encoding="utf-8")), (
        "OpenAPI drifted from contracts/openapi/p14-search.yaml - re-freeze only for an intended contract change"
    )


@pytest.mark.parametrize("name", [n for n in CONTRACT_MODELS if n not in ("IngestResult",)])
def test_frozen_schemas_agree_with_openapi_components(name):
    components = yaml.safe_load(OPENAPI.read_text(encoding="utf-8"))["components"]["schemas"]
    schema = frozen(name)
    component = components[name]
    assert set(schema.get("properties", {})) == set(component.get("properties", {}))
    assert set(schema.get("required", [])) == set(component.get("required", []))


def test_real_api_outputs_validate(loaded):
    body = loaded.post("/v1/search", json={"query": "lavoro agile"}, headers={"X-API-Key": "key-internal"}).json()
    validate("SearchResponse", body)
    pid = body["results"][0]["passages"][0]["passage_id"]
    validate("PassageInfo", loaded.get(f"/v1/passages/{pid}", headers={"X-API-Key": "key-internal"}).json())
    validate("DocumentInfo", loaded.get("/v1/documents/test:int-agile", headers={"X-API-Key": "key-internal"}).json())
    validate("Versions", loaded.get("/v1/version").json())
    problem = loaded.post("/v1/search", json={"query": ""}, headers={"X-API-Key": "key-internal"})
    assert problem.status_code == 422
    validate("Problem", problem.json())


EXAMPLES = sorted((ROOT / "contracts" / "examples").glob("*.json"))


@pytest.mark.parametrize("path", EXAMPLES, ids=[p.name for p in EXAMPLES])
def test_examples_validate(path):
    # File naming: <SchemaName>.<label>.json, e.g. SearchResponse.real.json
    validate(path.name.split(".")[0], json.loads(path.read_text(encoding="utf-8")))
